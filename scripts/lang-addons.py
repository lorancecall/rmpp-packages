#!/usr/bin/env python3
"""Make one Vellum package per rmpp-lang language add-on, and the installer's add-on list.

  python3 scripts/lang-addons.py [--src DIR]

The rmpp-lang repository and ref come from lang-addons.conf. Every languages/<code>/ there (format: rmpp-lang
docs/DESIGN.md, "Language add-ons") is built with the repository's own tools/build-addon.sh and becomes
packages/rmpp-lang-<code>/ (VELBUILD + <code>.tar.gz + <code>.rcc when the add-on has keyboards). The generated
folders are not committed: CI runs this before building, so a new folder in rmpp-lang is enough to publish a
language. The installer's list goes to site-addons/rmpp-lang.txt (published as addons/rmpp-lang.txt).
--src uses a local checkout instead of cloning.
"""
import argparse
import hashlib
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESERVED = {"en", "latin"}                # part of the rmpp-lang core; every other language is an add-on


def conf(path):
    d = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip().startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        d.setdefault(k.strip(), v.strip())
    return d


CODES_URL = "https://raw.githubusercontent.com/lorancecall/rmpp-hwr-db/main/scripts/languages.py"


def shared_codes():
    """The language codes shared by rmpp-hwr-db, rmpp-hwr and rmpp-lang (ISO 639-1 + variants), read as text from
    rmpp-hwr-db's scripts/languages.py (not imported). Empty set = not available, no check."""
    import urllib.request
    try:
        text = urllib.request.urlopen(CODES_URL, timeout=20).read().decode("utf-8")
    except OSError:
        print("note: could not read the shared language codes; add-on codes not checked")
        return set()
    iso = re.search(r'ISO_639_1 = set\("""(.*?)"""', text, re.S)
    var = re.search(r"VARIANTS = \{(.*?)\}", text)
    if not iso:
        return set()
    return set(iso.group(1).split()) | set(re.findall(r'"([a-z-]+)"', var.group(1) if var else ""))


def short(summary):
    """First part of a summary for the one-line menu entry: up to '(', ':' or ','."""
    s = re.split(r"\s*[(:,]", summary, maxsplit=1)[0].strip()
    return s if len(s) <= 34 else s[:33] + "…"


def pkgdesc(text):
    """apk pkgdesc: one line under 128 (abuild refuses longer; counted in UTF-8 bytes to be safe), cut at a word."""
    s = " ".join(text.replace('"', "'").split())
    if len(s.encode()) < 128:
        return s
    words = s.split(" ")
    while words and len((" ".join(words) + " ...").encode()) > 127:
        words.pop()
    return " ".join(words).rstrip(",;:") + " ..."


def wrap(text):
    return "|".join(textwrap.wrap(text, 60)[:3])


VELBUILD = """\
# Generated by scripts/lang-addons.py from {repo}@{ref} languages/{code}/: edit there, not here.
maintainer="lorancecall <84116812+lorancecall@users.noreply.github.com>"
pkgname=rmpp-lang-{code}
pkgver={version}
pkgrel=0
upstream_author="lorancecall"
category="ui"
pkgdesc="{desc}"
url="https://github.com/{repo}/tree/{ref}/languages/{code}"
arch="noarch"
license="{license}"
depends="rmpp-lang>={min_core}{requires}"
source="
{sources}
"
options="!check !fhs !strip"

# Files: /home/root/.local/share/rmpp-lang/languages/{code}/ (found by rmpp-lang while it runs){rcc_note}
# Never `systemctl stop xochitl`: that powers the tablet off. reset-failed avoids the restart limit.

package() {{
	mkdir -p "$pkgdir"/home/root/.local/share/rmpp-lang/languages/{code}
	cp -r "$srcdir"/{code}/. "$pkgdir"/home/root/.local/share/rmpp-lang/languages/{code}/
{rcc_package}{license_package}}}

postinstall() {{
	/home/root/.vellum/bin/mount-rw
	mkdir -p /usr/lib/rmpp-lang/languages
{rcc_copy}	sync
	[ -x /usr/bin/rmpp-lang ] && /usr/bin/rmpp-lang lang on {code} || true
{restart}	/home/root/.vellum/bin/mount-restore
}}

postupgrade() {{
	/home/root/.vellum/bin/mount-rw
	mkdir -p /usr/lib/rmpp-lang/languages
{rcc_copy}	sync
{restart}	/home/root/.vellum/bin/mount-restore
}}

# `vellum reenable` after an OS update: the root file system is already writable here.
postosupgrade() {{
	mkdir -p /usr/lib/rmpp-lang/languages
{rcc_copy}	sync
}}

predeinstall() {{
	/home/root/.vellum/bin/mount-rw
	rm -f /usr/lib/rmpp-lang/languages/{code}.rcc
	sync
{restart}	/home/root/.vellum/bin/mount-restore
}}
sha512sums="
{sums}
"
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", help="local rmpp-lang checkout (default: clone the repo/ref of lang-addons.conf)")
    a = ap.parse_args()
    cfg = conf(ROOT / "lang-addons.conf")
    repo, ref = cfg["repo"], cfg["ref"]
    tmp = Path(tempfile.mkdtemp(prefix="lang-addons-"))
    src = Path(a.src).resolve() if a.src else tmp / "src"
    if not a.src:
        subprocess.run(["git", "clone", "-q", "--depth", "1", "-b", ref, f"https://github.com/{repo}.git", str(src)],
                       check=True)
    codes = sorted(p.parent.name for p in (src / "languages").glob("*/language.conf") if p.parent.name not in RESERVED)
    allowed = shared_codes()
    if allowed:
        bad = [c for c in codes if c not in allowed]
        if bad:
            sys.exit(f"not ISO 639-1 or a known variant (rmpp-hwr-db scripts/languages.py): {', '.join(bad)}")
    for old in ROOT.glob("packages/rmpp-lang-*"):
        shutil.rmtree(old)
    if codes:
        subprocess.run(["sh", "tools/build-addon.sh", *codes], cwd=src, check=True)
    blocks = []
    for code in codes:
        c = conf(src / "languages" / code / "language.conf")
        if c.get("code") != code or c.get("format") != "1":
            sys.exit(f"languages/{code}/language.conf: code/format do not match")
        built = src / "build" / "languages" / code
        rcc = src / "build" / "languages" / f"{code}.rcc"
        out = ROOT / "packages" / f"rmpp-lang-{code}"
        out.mkdir(parents=True)
        tgz = out / f"{code}.tar.gz"
        with tarfile.open(tgz, "w:gz") as t:          # unpacked by vbuild into $srcdir/<code>/
            t.add(built, arcname=code, filter=lambda ti: ti.replace(uid=0, gid=0, uname="", gname="", mtime=0, deep=False))
        files = [tgz.name]
        if rcc.exists():
            shutil.copy(rcc, out / rcc.name)
            files.append(rcc.name)
        # requires=ko,...: other add-ons this one needs (e.g. ja/zh typed in Hangul need ko). Only the plain key
        # counts; per-input-method overrides (requires@<method>=) are for the core at run time.
        requires = [r.strip() for r in c.get("requires", "").split(",") if r.strip()]
        unknown = [r for r in requires if r not in codes or r == code]
        if unknown:
            sys.exit(f"languages/{code}/language.conf: requires= names unknown add-ons: {', '.join(unknown)}")
        req_pkgs = [f"rmpp-lang-{r}" for r in requires]
        fonts_license = (built / "LICENSE-fonts").exists()
        has_fonts = (built / "fonts").is_dir()
        sums = "\n".join(f"{hashlib.sha512((out / f).read_bytes()).hexdigest()}  {f}" for f in files)
        rcc_copy = (f"\tcp /home/root/.vellum/share/rmpp-lang-{code}/{code}.rcc /usr/lib/rmpp-lang/languages/{code}.rcc.new"
                    f" && chmod 644 /usr/lib/rmpp-lang/languages/{code}.rcc.new"
                    f" && mv -f /usr/lib/rmpp-lang/languages/{code}.rcc.new /usr/lib/rmpp-lang/languages/{code}.rcc\n"
                    if rcc.exists() else "")
        restart = ("\tsystemctl reset-failed xochitl 2>/dev/null || true\n\tsystemctl restart xochitl\n\tsleep 3\n"
                   if rcc.exists() else "")
        (out / "VELBUILD").write_text(VELBUILD.format(
            repo=repo, ref=ref, code=code, version=c.get("version", "0.1.0"), min_core=c.get("min_core", "0.1.0"),
            requires="".join(f" {p}" for p in req_pkgs),
            desc=pkgdesc(c.get("summary_en", c.get("name", code))),
            # extra licenses of bundled data (dictionaries...), per add-on in lang-addons.conf: license.<code>=
            license="GPL-3.0-only" + "".join(f" AND {x}" for x in cfg.get(f"license.{code}", "").split())
                    + (" AND custom" if has_fonts else ""),
            sources="\n".join(files), sums=sums,
            rcc_note=(f"\n# and {code}.rcc (keyboard layouts), copied to /usr/lib/rmpp-lang/languages/: xochitl loads it"
                      " at start, before /home is mounted" if rcc.exists() else ""),
            rcc_package=(f'\tinstall -Dm644 "$srcdir"/{code}.rcc "$pkgdir"/home/root/.vellum/share/rmpp-lang-{code}/{code}.rcc\n'
                         if rcc.exists() else ""),
            license_package=(f'\tinstall -Dm644 "$srcdir"/{code}/LICENSE-fonts "$pkgdir"/home/root/.vellum/licenses/$pkgname/LICENSE-fonts\n'
                             if fonts_license else ""),
            rcc_copy=rcc_copy, restart=restart), encoding="utf-8", newline="\n")
        kind_en = "keyboard and fonts" if c.get("input", "none") != "none" and has_fonts else (
            "keyboard" if c.get("input", "none") != "none" else "fonts")
        blocks.append("\n".join([
            f"id=rmpp-lang-{code}", "type=vellum", f"package=rmpp-lang-{code}", "needs=" + " ".join(["rmpp-lang", *req_pkgs]),
            *(["default=1"] if c.get("default") == "1" else []),   # preselected in the installer menu
            f"label=└ {code} {c.get('name', code)}",
            f"short_ko={short(c.get('summary_ko', c.get('name', code)))}",
            f"short_en={short(c.get('summary_en', c.get('name', code) + ' ' + kind_en))}",
            f"detail_ko={wrap(c.get('summary_ko', ''))}", f"detail_en={wrap(c.get('summary_en', ''))}"]))
        print(f"packages/rmpp-lang-{code}: {c.get('version')} ({', '.join(files)})")
    site = ROOT / "site-addons"
    site.mkdir(exist_ok=True)
    (site / "rmpp-lang.txt").write_text(
        "# rmpp-lang language add-ons for the rmpp installer (generated by scripts/lang-addons.py)\n"
        + "\n---\n".join(blocks) + "\n", encoding="utf-8", newline="\n")
    print(f"site-addons/rmpp-lang.txt: {len(blocks)} add-on(s)")
    shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()
