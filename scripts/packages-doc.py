#!/usr/bin/env python3
"""Write docs/packages.md: every rmpp package, what it installs with it, what needs it, its installer menu entry.

Sources: packages/*/VELBUILD (the add-ons' own VELBUILDs are fetched there by scripts/registry.py, the
rmpp-lang-<code> add-ons are generated by scripts/lang-addons.py) and the installer catalog (mods.txt + each
repository's rmpp-mod.conf, downloaded). Run after scripts/registry.py and scripts/lang-addons.py;
--check exits 1 when docs/packages.md is out of date (CI runs it on pull requests).
"""
import argparse
import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "packages.md"
SYSTEM = re.compile(r"^(mount-utils|remarkable-os.*)$")  # tablet checks, not add-ons


def velbuild(path):
    text = path.read_text(encoding="utf-8")
    def var(name):
        m = re.search(rf'^{name}="?(.*?)"?$', text, re.M)
        return m.group(1) if m else ""
    deps, conflicts = [], []
    for d in var("depends").split():
        name = re.split(r"[<>=]", d)[0]
        if name.startswith("!"):
            conflicts.append(name[1:])
        elif not SYSTEM.match(name):
            deps.append(name)
    return {"name": var("pkgname"), "desc": var("pkgdesc"), "url": var("url"), "deps": deps,
            "conflicts": [c for c in conflicts if c not in ("rm1", "rm2")]}


def catalog():
    """Installer menu entries: {id: conf} from mods.txt and each repository's rmpp-mod.conf."""
    mods = {}
    for line in (ROOT / "mods.txt").read_text(encoding="utf-8").splitlines():
        repo = line.strip()
        if not repo or repo.startswith("#"):
            continue
        url = f"https://raw.githubusercontent.com/{repo}/main/rmpp-mod.conf"
        try:
            conf = urllib.request.urlopen(url, timeout=30).read().decode("utf-8")
        except OSError as e:
            sys.exit(f"{url}: {e}")
        kv = dict(l.split("=", 1) for l in conf.splitlines() if "=" in l and not l.startswith("#"))
        kv["repo"] = repo
        mods[kv["id"]] = kv
    return mods


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if docs/packages.md would change")
    args = ap.parse_args()

    pkgs = {p["name"]: p for p in (velbuild(v) for v in sorted(ROOT.glob("packages/*/VELBUILD")))}
    mods = catalog()
    menu = {}  # package -> menu entry
    for m in mods.values():
        for p in m.get("package", "").split():
            menu.setdefault(p, m.get("short_en", m["id"]))
    for f in sorted((ROOT / "addons").glob("*.txt")):  # hand-written add-on lists (rmpp-hwr's models, ...)
        for block in f.read_text(encoding="utf-8").split("\n---"):
            kv = dict(l.split("=", 1) for l in block.splitlines() if "=" in l and not l.startswith("#"))
            if kv.get("package"):
                parent = next((m.get("short_en", m["id"]) for m in mods.values()
                               if m.get("package") in kv.get("needs", "").split()), "")
                menu.setdefault(kv["package"], f"{kv.get('short_en', kv['package'])}, under {parent}" if parent
                                else kv.get("short_en", kv["package"]))
    needed_by = {n: sorted(p["name"] for p in pkgs.values() if n in p["deps"]) for n in pkgs}

    def closure(n, seen=None):
        seen = set() if seen is None else seen
        for d in pkgs.get(n, {}).get("deps", []):
            if d not in seen:
                seen.add(d)
                closure(d, seen)
        return seen

    def code(xs):
        return ", ".join(f"`{x}`" for x in xs) or "-"

    rows = []
    for n in sorted(pkgs, key=lambda n: (n != "rmpp-preload", n)):
        p = pkgs[n]
        entry = menu.get(n, "")
        if not entry and n.startswith("rmpp-lang-"):
            entry = "a language under Languages"
        elif not entry and n == "rmpp-preload":
            entry = "(always, with any add-on)"
        rows.append(f"| `{n}` | {p['desc']} | {code(sorted(closure(n)))} | {code(needed_by[n])} | {entry or '-'} |")

    release = [m for m in mods.values() if m.get("type") == "release"]
    rel_rows = [f"| {m['id']} | {m.get('short_en', '')} | {code(m.get('needs', '').split())} | "
                f"[{m['repo'].split('/')[1]}](https://github.com/{m['repo']}) |" for m in release]
    conflicts = [f"- `{n}` cannot be installed next to {code(p['conflicts'])} (they do the same): remove those first." for n, p in sorted(pkgs.items())
                 if p["conflicts"]]

    doc = f"""# Packages and dependencies

<!-- Generated by scripts/packages-doc.py from packages/*/VELBUILD and the installer catalog: do not edit. -->

The rmpp add-ons are [Vellum](https://github.com/vellum-dev/vellum) packages (apk), apart from the mods listed further
down. Installing a package installs what it depends on, in rmpp setup and with `vellum add` alike. Removing one
keeps every package another installed package still needs: apk says so and leaves it in place. How to install and
remove: [manual-install.md](manual-install.md), [uninstall.md](uninstall.md).

| Package | What it does | Installs with it | Needed by | rmpp setup menu |
|---|---|---|---|---|
{chr(10).join(rows)}

"Installs with it" counts everything pulled in, also indirectly. All packages also check the device (reMarkable
Paper Pro, OS 3.29) and refuse to install elsewhere.
"""
    if rel_rows:
        doc += f"""
## Mods that are not Vellum packages (yet)

The installer menu also offers these. rmpp setup downloads them from the project's latest GitHub release and runs
its install script. Vellum does not track them: nothing checks their dependencies when something is removed, only
**Remove everything** removes them, and **Restore** does not bring them back after an OS update (install them again).

| Mod | rmpp setup menu | Installed first | Project |
|---|---|---|---|
{chr(10).join(rel_rows)}
"""
    if conflicts:
        doc += "\n## Packages that cannot be installed together\n\n" + "\n".join(conflicts) + "\n"

    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != doc:
            sys.exit("docs/packages.md is out of date: run scripts/lang-addons.py, then scripts/packages-doc.py")
        return
    OUT.write_text(doc, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} packages, {len(rel_rows)} release mods")


if __name__ == "__main__":
    main()
